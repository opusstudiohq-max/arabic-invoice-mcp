#!/usr/bin/env python3
"""
مخرَجٌ عربيٌّ لا ينهار حين يُعاد توجيهه.

### القصّة

كلُّ أدواتنا تطبع بالعربية وبعلامة «✓». وبايثون على ويندوز يختار ترميز
المخرَج من **المحليّة** حين لا يكون المخرَج طرفيةً حقيقية — أي عند إعادة
التوجيه إلى ملف، أو الأنبوب، أو الالتقاط في سجلّ. والمحليّة هنا `cp1252`،
ولا مكان فيها للعربية ولا لـ«✓».

فالنتيجة `UnicodeEncodeError` **عند أول سطر طباعة**.

وأخطرُ موضعٍ وقع فيه هذا `backup_repo.py`: يبني الحزمة، ثم يموت عند أول
`print` — **قبل التحقق من الاستعادة وقبل الرفع**. فمن كتب
`python tools/backup_repo.py > backup.log` ظنّ أنه نسخ، ولا نسخة له خارج
الجهاز. وهو رابع عيبٍ في الأداة التي تحرس ما لا يُعوَّض.

### لماذا لم يظهر طوال العمل

كان `PYTHONIOENCODING=utf-8` مُصدَّراً في صدفة من كتب الأدوات، فما رآها
تنهار قطّ. **والأداة تُقاس في بيئة مُشغِّلها لا في بيئة كاتبها.**

### حدُّ ما قِيس

قِيس الانهيار عند إعادة التوجيه إلى ملف وعند الأنبوب. أما الطرفيةُ
التفاعلية الحقيقية فبايثون يكتب فيها بـ`WriteConsoleW` فينجو غالباً —
**ولم يُقَس ذلك هنا**، فلا يُدَّعى.
"""
from __future__ import annotations

import sys


def utf8_stdio() -> None:
    """
    يُثبّت مخرَجَي العملية على UTF-8 مهما كانت المحليّة.

    يُستدعى **قبل argparse** — فوصفُ الأداة ورسائل `--help` عربية أيضاً،
    و`--help` وحده كان ينهار في الإحدى عشرة أداة كلّها.
    """
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8")
        except (AttributeError, ValueError):
            # مجرىً مُستبدَل (اختبارٌ يلتقط، أو بايثون قديم) — لا يُكسر شيء
            pass
